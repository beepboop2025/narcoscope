#!/usr/bin/env node
/**
 * Builds the US-state reference that joins CDC overdose data to the map.
 *
 * CDC keys jurisdictions by two-letter abbreviation (CA); the us-atlas topojson
 * keys states by FIPS code (06). This emits src/data/usStates.ts — one row per
 * jurisdiction with { abbr, fips, name, population } — so the State Overdose tab
 * can (a) colour the choropleth by joining CDC → FIPS, and (b) turn raw death
 * counts into rates per 100k, which is the only honest cross-state comparison
 * (raw counts just track population).
 *
 * Populations are 2023 US Census Bureau estimates — public, stable, and used
 * only as a denominator. They are keyed by abbreviation below and joined to the
 * FIPS/name from the bundled topojson so the two never drift.
 *
 * Usage: node scripts/convert/gen-us-states.mjs [path-to-states-topojson]
 *   (defaults to src/data/us-states-10m.json, which this also verifies exists)
 */

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..')
const TOPO = process.argv[2] || path.join(ROOT, 'src/data/us-states-10m.json')

// 2023 Census population estimates, by CDC jurisdiction abbreviation.
// 'US' national is included for context; 'YC' (NYC) shares NY's data grain and
// is given NYC's ~8.26M so its rate is not computed against the whole state.
const POPULATION = {
  US: 334914895,
  AL: 5108468, AK: 733406, AZ: 7431344, AR: 3067732, CA: 38965193,
  CO: 5877610, CT: 3617176, DE: 1031890, DC: 678972, FL: 22610726,
  GA: 11029227, HI: 1435138, ID: 1964726, IL: 12549689, IN: 6862199,
  IA: 3207004, KS: 2940546, KY: 4526154, LA: 4573749, ME: 1395722,
  MD: 6180253, MA: 7001399, MI: 10037261, MN: 5737915, MS: 2939690,
  MO: 6196156, MT: 1132812, NE: 1978379, NV: 3194176, NH: 1402054,
  NJ: 9290841, NM: 2114371, NY: 19571216, NC: 10835491, ND: 783926,
  OH: 11785935, OK: 4053824, OR: 4233358, PA: 12961683, RI: 1095962,
  SC: 5373555, SD: 919318, TN: 7126489, TX: 30503301, UT: 3417734,
  VT: 647464, VA: 8715698, WA: 7812880, WV: 1770071, WI: 5910955,
  WY: 584057, YC: 8258035,
}

// Full state name -> abbreviation, to bridge the topojson (name) and CDC (abbr).
const NAME_TO_ABBR = {
  Alabama: 'AL', Alaska: 'AK', Arizona: 'AZ', Arkansas: 'AR', California: 'CA',
  Colorado: 'CO', Connecticut: 'CT', Delaware: 'DE', 'District of Columbia': 'DC',
  Florida: 'FL', Georgia: 'GA', Hawaii: 'HI', Idaho: 'ID', Illinois: 'IL',
  Indiana: 'IN', Iowa: 'IA', Kansas: 'KS', Kentucky: 'KY', Louisiana: 'LA',
  Maine: 'ME', Maryland: 'MD', Massachusetts: 'MA', Michigan: 'MI', Minnesota: 'MN',
  Mississippi: 'MS', Missouri: 'MO', Montana: 'MT', Nebraska: 'NE', Nevada: 'NV',
  'New Hampshire': 'NH', 'New Jersey': 'NJ', 'New Mexico': 'NM', 'New York': 'NY',
  'North Carolina': 'NC', 'North Dakota': 'ND', Ohio: 'OH', Oklahoma: 'OK',
  Oregon: 'OR', Pennsylvania: 'PA', 'Rhode Island': 'RI', 'South Carolina': 'SC',
  'South Dakota': 'SD', Tennessee: 'TN', Texas: 'TX', Utah: 'UT', Vermont: 'VT',
  Virginia: 'VA', Washington: 'WA', 'West Virginia': 'WV', Wisconsin: 'WI',
  Wyoming: 'WY',
}

if (!fs.existsSync(TOPO)) {
  console.error(`ERROR: topojson not found at ${TOPO}. Fetch us-atlas states-10m.json first.`)
  process.exit(1)
}
const topo = JSON.parse(fs.readFileSync(TOPO, 'utf8'))
const geometries = topo.objects.states.geometries

const rows = []
const skipped = []
for (const g of geometries) {
  const name = g.properties?.name
  const abbr = NAME_TO_ABBR[name]
  if (!abbr) { skipped.push(name); continue } // territories (PR, GU, ...) — no CDC row
  rows.push({ abbr, fips: g.id, name, population: POPULATION[abbr] ?? null })
}
rows.sort((a, b) => a.name.localeCompare(b.name))

const missingPop = rows.filter((r) => r.population == null).map((r) => r.abbr)
if (missingPop.length) {
  console.error(`ERROR: missing population for ${missingPop.join(', ')}`)
  process.exit(1)
}

const out = `// GENERATED by scripts/convert/gen-us-states.mjs — do not edit by hand.
// Joins CDC overdose jurisdictions (by abbr) to the us-atlas choropleth (by
// FIPS), and carries 2023 Census population for per-100k rates.
export interface UsState { abbr: string; fips: string; name: string; population: number }

export const US_STATES: UsState[] = ${JSON.stringify(rows, null, 2)}

/** NYC ('YC') is a CDC jurisdiction with no separate map shape; rates only. */
export const US_JURISDICTION_POP: Record<string, number> = ${JSON.stringify(
  { YC: POPULATION.YC, US: POPULATION.US }, null, 2,
)}

export const FIPS_TO_ABBR: Record<string, string> =
  Object.fromEntries(US_STATES.map((s) => [s.fips, s.abbr]))
`
const OUT = path.join(ROOT, 'src/data/usStates.ts')
fs.writeFileSync(OUT, out)
console.log(`✔ wrote usStates.ts — ${rows.length} states${skipped.length ? `, skipped ${skipped.length} non-CDC territories (${skipped.join(', ')})` : ''}`)
